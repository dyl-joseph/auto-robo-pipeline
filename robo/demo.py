"""Deterministic illustrated robot fixtures. No physical robot or learned model."""

import subprocess
from pathlib import Path

import cv2
import numpy as np

from robo.analysis import suggest
from robo.core import atomic_json
from robo.ingest import import_episode
from robo.store import Store


def make_demo(root: Path, count: int = 6) -> list[dict]:
    store = Store(root)
    raw = root / "demo_sources"
    raw.mkdir(exist_ok=True)
    result = []
    for index in range(count):
        path = raw / f"tabletop-{index}.mp4"
        length, fps = 8, 12
        if not path.exists():
            process = subprocess.Popen(
                [
                    "ffmpeg",
                    "-v",
                    "error",
                    "-f",
                    "rawvideo",
                    "-pixel_format",
                    "bgr24",
                    "-video_size",
                    "640x360",
                    "-framerate",
                    str(fps),
                    "-i",
                    "pipe:0",
                    "-an",
                    "-c:v",
                    "libx264",
                    "-threads",
                    "1",
                    "-pix_fmt",
                    "yuv420p",
                    "-y",
                    str(path),
                ],
                stdin=subprocess.PIPE,
            )
            for frame in range(length * fps):
                t = frame / fps
                image = np.full((360, 640, 3), (35, 31, 24), dtype=np.uint8)
                for x in range(40, 640, 40):
                    cv2.line(image, (x, 90), (x, 330), (53, 46, 34), 1)
                for y in range(90, 331, 40):
                    cv2.line(image, (30, y), (610, y), (53, 46, 34), 1)
                cv2.rectangle(image, (430, 145), (550, 250), (105, 88, 64), 2)
                cv2.putText(image, "TARGET", (447, 280), 0, 0.5, (169, 151, 117), 1)
                reach = min(t / 2, 1)
                carry = np.clip((t - 3) / 3, 0, 1)
                x = int(165 + 30 * reach + 285 * carry)
                y = int(118 + 82 * reach - 50 * np.sin(carry * np.pi))
                if index % 2 and 4.5 < t < 5.5:
                    y += int(35 * np.sin((t - 4.5) * np.pi))
                base, elbow = (70, 300), (110, 130)
                cv2.line(image, base, elbow, (173, 169, 151), 17)
                cv2.line(image, elbow, (x, y - 25), (207, 204, 187), 13)
                cv2.circle(image, elbow, 15, (72, 70, 57), -1)
                opening = 18 if t < 2.5 or t > 6.5 else 9
                for sign in (-1, 1):
                    cv2.line(
                        image,
                        (x + sign * opening, y - 20),
                        (x + sign * opening, y + 10),
                        (235, 223, 191),
                        4,
                    )
                ox = x if 2.5 < t < 6.5 else (195 if t <= 2.5 else 480)
                cv2.rectangle(image, (ox - 13, 203 - 13), (ox + 13, 203 + 13), (105, 200, 220), -1)
                cv2.putText(
                    image, "SYNTHETIC / TABLETOP TRANSFER", (26, 30), 0, 0.6, (192, 206, 215), 1
                )
                cv2.putText(
                    image,
                    f"camera 01   episode {index + 1:02d}   {t:05.2f}s",
                    (26, 54),
                    0,
                    0.45,
                    (133, 151, 159),
                    1,
                )
                if index == 4 and 3 < t < 4:
                    image = cv2.GaussianBlur(image, (31, 31), 10)
                process.stdin.write(image.tobytes())
            process.stdin.close()
            if process.wait(timeout=30):
                raise RuntimeError("demo video encoding failed")
        times = np.arange(0, length, 1 / fps).tolist()
        source = {
            "source_id": f"illustrated-tabletop-{index}",
            "release": "demo-v1",
            "task": "Transfer cube" if index < 4 else "Reposition cube",
            "session": f"demo-session-{index // 2}",
            "video": path.name,
            "license": "CC0-1.0",
            "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
            "provenance": (
                "Generated by robo.demo v1; 2D illustration, "
                "no physical dynamics or robot measurements"
            ),
            "data_kind": "synthetic",
            "streams": [],
        }
        if index != 5:
            source["streams"] = [
                {
                    "name": "gripper",
                    "modality": "state",
                    "units": "normalized",
                    "timestamps_s": times,
                    "values": [[float(t < 2.5 or t > 6.5)] for t in times],
                    "clock_evidence": "same generated fixture clock",
                    "tolerance_s": 0.05,
                },
                {
                    "name": "command",
                    "modality": "action",
                    "units": "normalized",
                    "timestamps_s": times,
                    "values": [[float(3 < t < 6)] for t in times],
                    "clock_evidence": "same generated fixture clock",
                    "tolerance_s": 0.05,
                },
            ]
        manifest = raw / f"source-{index}.json"
        atomic_json(manifest, source)
        episode = import_episode(manifest, store)
        suggest(store, episode["id"])
        result.append(episode)
    return result
